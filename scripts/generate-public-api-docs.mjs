import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import ts from 'typescript'

const root = resolve(import.meta.dirname, '..')
const manifestPath = resolve(root, 'packages/content/package.json')
const declarationsPath = resolve(root, 'packages/content/src/public/data-source.ts')
const outputPath = resolve(root, 'docs/content/docs/9.api-reference/7.data-source.md')

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
const declarationSource = await readFile(declarationsPath, 'utf8')
const sourceFile = ts.createSourceFile(
  declarationsPath,
  declarationSource,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TS,
)

const isExported = node => node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
const declarations = []

for (const statement of sourceFile.statements) {
  if (!isExported(statement)) continue
  if (ts.isInterfaceDeclaration(statement)) {
    declarations.push([statement.name.text, 'interface'])
  } else if (ts.isTypeAliasDeclaration(statement)) {
    declarations.push([statement.name.text, 'type'])
  } else if (ts.isVariableStatement(statement)) {
    for (const item of statement.declarationList.declarations) {
      if (ts.isIdentifier(item.name)) declarations.push([item.name.text, 'const'])
    }
  }
}

declarations.sort(([left], [right]) => left.localeCompare(right))

const subpaths = Object.entries(manifest.exports)
  .map(([subpath, target]) => {
    const specifier = subpath === '.' ? manifest.name : `${manifest.name}${subpath.slice(1)}`
    const types = typeof target === 'string' ? target : target.types
    return `| \`${specifier}\` | \`${types}\` |`
  })
  .sort()

const generated = `---
title: Data-source API
description: Generated package subpaths and pure data-source declarations.
---

# Data-source API

This file is generated by \`pnpm api-docs:generate\`. The package manifest is
the subpath authority, and the public TypeScript declaration source is the API
name authority. The canonical adapter author guide is
\`packages/content/docs/DATA_SOURCE_ADAPTER_GUIDE.md\`.

## Package subpaths

| Import | Types |
| --- | --- |
${subpaths.join('\n')}

## Pure data-source declarations

Source: \`packages/content/src/public/data-source.ts\`.

| Name | Kind |
| --- | --- |
${declarations.map(([name, kind]) => `| \`${name}\` | ${kind} |`).join('\n')}
`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('Generated data-source API documentation is stale. Run pnpm api-docs:generate.')
    process.exit(1)
  }
} else {
  await writeFile(outputPath, generated)
}
